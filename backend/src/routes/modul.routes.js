const express = require('express')
const router = express.Router()
const category = require('../controllers/kategoriPanduan.controller')
const ctrl = require('../controllers/modul.controller')
const { requireAuth } = require('../middleware/auth')
router.use(requireAuth)
router.use(express.json({ limit: '100mb' }))
const safe = handler => (req, res, next) => Promise.resolve(handler(req, res)).catch(next)
router.get('/kategori', safe(category.getAll))
router.post('/kategori', safe(category.create))
router.put('/kategori/:id', safe(category.update))
router.delete('/kategori/:id', safe(category.remove))
router.get('/', safe(ctrl.getAll))
router.post('/', safe(ctrl.create))
router.get('/:id/file', safe(ctrl.download))
router.put('/:id', safe(ctrl.update))
router.delete('/:id', safe(ctrl.remove))
router.use((err, req, res, next) => {
  if (err.code === 'ER_DUP_ENTRY') return res.status(409).json({ message: 'Nama kategori sudah digunakan.' })
  if (err.code === 'ER_ROW_IS_REFERENCED_2') return res.status(409).json({ message: 'Kategori masih digunakan. Pindahkan panduannya dahulu.' })
  if (err.code === 'ER_NO_REFERENCED_ROW_2') return res.status(400).json({ message: 'Kategori tidak tersedia. Muat ulang daftar kategori.' })
  if (err.status === 400 || err.status === 413) return res.status(err.status).json({ message: err.status === 413 ? 'File maksimal 60 MB.' : err.message })
  next(err)
})
module.exports = router
